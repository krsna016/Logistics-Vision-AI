## 13. लेयर हिस्ट्री, सुधार और हटाना

हर सेव लेयर में नंबर, कार्टन, आइटम मात्रा, डिफेक्ट, फोटो, नोट, ऑपरेटर और समय दिखता है।

लेयर की reference photo दबाकर verification viewer खोलें। ऊपर compact bar में zoom करते समय भी layer number और total cartons दिखते हैं। Mask और carton number को अलग-अलग चालू या बंद कर सकते हैं। स्प्लिट (Split) लेयर के लिए, आपको हेडर में LEFT SIDE / RIGHT SIDE टॉगल भी दिखाई देगा जिससे आप दोनों फोटो और उनकी गिनती आसानी से देख सकें। Editable layer में खाली जगह दबाने पर missing carton जुड़ता है, existing carton outline दबाने पर वह हटता है और उसी जगह फिर दबाने पर वापस आ जाता है—बिल्कुल Review screen की तरह। ये preview बदलाव अस्थायी हैं और अपने आप save नहीं होते। बदलाव के बाद image बंद करने, बाहर tap करने या Android back/swipe करने पर चेतावनी आती है। **Discard** से बदलाव हटा दें या **Go to correction** से preview के boxes साथ लेकर सामान्य Layer Correction page खोलें और वहां स्पष्ट रूप से save करें। पुराने layer में AI polygon न हो तो भी editable layer में carton manually जोड़ा जा सकता है।

### पुरानी लेयर सुधारना

लेयर का Edit खोलें। आप कार्टन, मिश्रित आइटम, डिफेक्ट और Notes बदल सकते हैं। मैनिफेस्ट होने पर कार्टन आइटम मात्रा से अपने आप निकलता है। संख्या या आइटम बदलने पर साफ कारण लिखें।

अच्छा कारण: `भौतिक दोबारा गिनती में Item B के 2 अतिरिक्त कार्टन मिले।`

### लेयर हटाना

Layer History card के सबसे दाईं ओर circular delete button से पूरी लेयर गलत या डुप्लिकेट हो तभी Remove Layer करें। मांगा गया लेयर नंबर टाइप करके पुष्टि करें। इससे वाहन कुल, वैगन इन्वेंटरी और रिपोर्ट फिर से गणना होती है। ऑडिट में कार्रवाई रहती है।

गलती छिपाने के लिए सही लेयर न हटाएं। उसे कारण के साथ सुधारें।

### Offline Unique ID System (UUIDs)

चूंकि SmartLoad पूरी तरह से ऑफ़लाइन काम करता है, इसलिए यह रिकॉर्ड की पहचान करने के लिए सरल नंबरों (जैसे Wagon #1, Wagon #2) पर निर्भर नहीं करता है। इसके बजाय, यह हर रिकॉर्ड के लिए 36-अक्षरों का एक जटिल और पूरी तरह से अद्वितीय UUID (Universally Unique Identifier) जनरेट करता है।

इसके दो बहुत बड़े फायदे हैं:
1. **एक ही नाम सुरक्षित है (Name Duplication is Safe):** आप "Train Express A" नाम से दो वैगन या एक ही नंबर प्लेट वाले दो ट्रक बना सकते हैं। चूँकि उनके छिपे हुए UUID पूरी तरह से अलग होंगे, सिस्टम कभी भी उनके लेयर, फोटो या इन्वेंट्री को आपस में नहीं मिलाएगा।
2. **ऑफ़लाइन सुरक्षा (Offline Safety):** बिना इंटरनेट वाले दो अलग-अलग गोदामों में काम कर रहे दो ऑपरेटर कभी भी गलती से एक ही ID जनरेट नहीं कर सकते। जब उनका डेटा बैकअप के ज़रिए एक जगह लाया जाता है, तो कोई डेटा आपस में नहीं टकराता। हर वैगन, ट्रक, लेयर, फोटो और ऑडिट लॉग की अपनी एक 100% यूनिक ID होती है।

