## 4. वैगन कंट्रोल सेंटर

यह ऐप की मुख्य स्क्रीन है।

### ऊपर के सारांश कार्ड

- Active Wagons: अभी योजना या लोडिंग में चल रहे वैगन।
- Total Trucks: वर्तमान रिकॉर्ड से जुड़े वाहन।
- Total Cartons: वाहन की सेव लेयर में दर्ज कार्टन।

### वैगन कार्ड

कार्ड में वैगन नंबर, स्थिति, वाहन संख्या, कार्टन और इन्वेंटरी प्रगति दिखती है। Wagon Details खोलने के लिए कार्ड दबाएं।

### सर्च और फिल्टर

- सर्च बॉक्स से वैगन खोजें।
- All सभी रिकॉर्ड दिखाता है।
- Planning में बने हुए लेकिन शुरू न हुए वैगन दिखते हैं।
- Loading सक्रिय लोडिंग दिखाता है।
- Completed पूरा किया हुआ काम दिखाता है।
- नीचे खींचकर डेटा रिफ्रेश करें।

### लोडिंग सिलेक्टर बार (Loading Selector Bar)

जब किसी वैगन की लोडिंग चल रही हो, तो स्क्रीन के नीचे एक सिलेक्टर बार दिखाई देता है।
- वैगन से जुड़े ट्रक देखने के लिए इस बार को ऊपर खींचें।
- अपनी पसंद का मोड चुनने के लिए बार के ऊपरी-दाएं कोने में मौजूद **AI MODE / MANUAL** टॉगल का उपयोग करें।
- किसी भी ट्रक पर टैप करने से वह सीधा कैमरे (यदि AI MODE चुना है) या मैन्युअल एंट्री स्क्रीन (यदि MANUAL चुना है) पर चला जाएगा।

### मुख्य मेनू

- Digital Registers: वैगन इतिहास और रिपोर्ट।
- Documentation: यह अंग्रेजी और हिंदी पुस्तिका।
- AI Camera Settings: Confidence, Overlap/IoU, crop quality, processing power और detailed outlines की स्थानीय सेटिंग बदलें। **Save locally** दबाएं; जरूरत हो तो **Reset recommended settings** चुनें।
- Load Demo Data: केवल Administrator के लिए; वर्तमान लोकल डेटा हटाकर प्रशिक्षण डेटा बनाता है।
- Logout: वर्तमान उपयोगकर्ता सेशन बंद करता है।

Administrator को **Backup & Restore** भी मिलता है। इससे database, photos, audit records और exports का local archive बनाकर share किया जा सकता है, SmartLoad ZIP या extracted folder import किया जा सकता है और पुराना local backup restore किया जा सकता है। Import या restore से पहले archive और तारीख ध्यान से जांचें।

